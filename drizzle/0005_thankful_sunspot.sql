CREATE TABLE IF NOT EXISTS `meta_ad_insights` (
	`id` int AUTO_INCREMENT NOT NULL,
	`accountId` varchar(64) NOT NULL,
	`currency` varchar(12) NOT NULL DEFAULT 'USD',
	`dateStart` date NOT NULL,
	`dateStop` date NOT NULL,
	`level` varchar(16) NOT NULL DEFAULT 'ad',
	`campaignId` varchar(80) NOT NULL,
	`campaignName` varchar(180) NOT NULL,
	`adsetId` varchar(80),
	`adsetName` varchar(180),
	`adId` varchar(80) NOT NULL,
	`adName` varchar(180) NOT NULL,
	`impressions` int NOT NULL DEFAULT 0,
	`reach` int NOT NULL DEFAULT 0,
	`frequency` decimal(10,4) NOT NULL DEFAULT '0',
	`clicksAll` int NOT NULL DEFAULT 0,
	`linkClicks` int NOT NULL DEFAULT 0,
	`spend` decimal(12,2) NOT NULL DEFAULT '0',
	`ctr` decimal(10,4) NOT NULL DEFAULT '0',
	`inlineLinkClickCtr` decimal(10,4) NOT NULL DEFAULT '0',
	`cpc` decimal(12,4) NOT NULL DEFAULT '0',
	`costPerLinkClick` decimal(12,4) NOT NULL DEFAULT '0',
	`cpm` decimal(12,4) NOT NULL DEFAULT '0',
	`messagingConversations` int NOT NULL DEFAULT 0,
	`messagingReplies` int NOT NULL DEFAULT 0,
	`messagingConnections` int NOT NULL DEFAULT 0,
	`messagingFirstReplies` int NOT NULL DEFAULT 0,
	`messagingDepth2` int NOT NULL DEFAULT 0,
	`messagingDepth3` int NOT NULL DEFAULT 0,
	`videoViews` int NOT NULL DEFAULT 0,
	`syncedAt` timestamp NOT NULL DEFAULT (now()),
	CONSTRAINT `meta_ad_insights_id` PRIMARY KEY(`id`),
	CONSTRAINT `meta_ad_insights_unique_idx` UNIQUE(`accountId`,`level`,`adId`,`dateStart`,`dateStop`)
);
